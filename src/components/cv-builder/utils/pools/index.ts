// ✅ GET BULLETS DYNAMICALLY
// ============================================
export const getProfessionBullets = (
    profession: string,
    level: string,
    company: string
): string[] => {
    const poolFn = professionPoolMap[profession];
    if (poolFn) {
        return poolFn(level, company);
    }
    // Ultimate fallback — General
    return getGeneralBullets(level, company);
};

